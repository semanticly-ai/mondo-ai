"""Render the curation rule registry as a published value set.

The SSSOM `curation_rule` slot is URI-valued, so a row can say
``maprule:SC-002|maprule:PR-002`` instead of carrying a paragraph of prose in every cell.
That only works if the CURIEs mean something to a reader, which is what this module
produces: the same registry in three shapes, all generated from :mod:`mondo_ai.align.rules`
so none of them can drift from the code that cites them.

| Artefact | For |
|---|---|
| ``maprule.yaml`` | a LinkML enum, so the rule set can be imported and validated against |
| ``maprule.ttl`` | a SKOS concept scheme, so ``maprule:SC-002`` resolves to a definition |
| ``maprule.md`` | the human registry, one table per family |

Two machine-readable properties travel with each concept, because they are the two facts a
downstream tool actually needs to act on: whether the rule forbids ``skos:exactMatch``, and
whether it is a terminal reason not to map at all.

Example:
    >>> "maprule:SC-001" in render_skos()
    True
    >>> "SC-001" in render_linkml()
    True
    >>> render_markdown().splitlines()[0]
    '# Mapping curation rules — `maprule`'
"""

from __future__ import annotations

from pathlib import Path

from mondo_ai.align.rules import (
    FAMILIES,
    MAPRULE_PREFIX,
    MAPRULE_URI_BASE,
    REGISTRY,
    family_ids,
)

#: Human-readable name of each family, used as the heading and as the SKOS collection label.
FAMILY_TITLES = {
    "EV": "Evidence for sameness",
    "SC": "Scope, granularity and undefined subsets",
    "PR": "Predicate selection",
    "ST": "Structural integrity",
    "RJ": "Rejection grounds",
    "CM": "Conceptual model conflation (disease / phenotype)",
}

#: What each family is for, in one sentence.
FAMILY_SCOPE = {
    "EV": "What was actually observed that supports the mapping. Records evidence, not a "
          "verdict.",
    "SC": "Where the two concepts differ in extension rather than in kind.",
    "PR": "Which predicate the relation found actually licenses. Direction convention: in "
          "`subject predicate object`, `skos:narrowMatch` means the OBJECT is narrower.",
    "ST": "Checks over the set rather than the row. Violations are set-level defects.",
    "RJ": "Terminal outcomes. A rejection is a finding and is recorded, not dropped.",
    "CM": "The two resources hold genuinely different models of what an entity is, and the "
          "curator crossed that boundary knowingly. Conflation is a decision, not an error.",
}

SCHEME_URI = f"{MAPRULE_URI_BASE}maprule"


def _esc(text: str) -> str:
    """Escape a string for a Turtle literal.

    Example:
        >>> _esc('an "Other X" rubric')
        'an \\\\"Other X\\\\" rubric'
    """
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def render_skos() -> str:
    """Render the registry as a SKOS concept scheme in Turtle.

    Each rule is a ``skos:Concept`` with a ``skos:notation``, a ``prefLabel`` and a
    ``definition``, gathered under a per-family ``skos:Collection``. The two action-bearing
    facts are exposed as typed properties rather than buried in the definition text.

    Example:
        >>> ttl = render_skos()
        >>> "maprule:SC-001 a skos:Concept" in ttl
        True
        >>> "maprule:blocksExactMatch true" in ttl
        True
        >>> 'skos:notation "SC-001"' in ttl
        True
    """
    lines = [
        "@prefix maprule: <%s> ." % MAPRULE_URI_BASE,
        "@prefix skos: <http://www.w3.org/2004/02/skos/core#> .",
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
        "@prefix dcterms: <http://purl.org/dc/terms/> .",
        "",
        "# Generated by `just align-valueset` from mondo_ai.align.rules. Do not hand-edit.",
        "",
        f"<{SCHEME_URI}> a skos:ConceptScheme ;",
        '    dcterms:title "Mapping curation rules" ;',
        '    dcterms:description "Named, citable rules for curating and reviewing mappings. '
        "A mapping decision is only meaningful relative to the rules it was made under, so "
        'these ids are what SSSOM curation_rule cells carry." ;',
        f'    skos:hasTopConcept {", ".join(f"maprule:{f}" for f in FAMILIES)} .',
        "",
        "maprule:blocksExactMatch a owl:DatatypeProperty ;",
        '    rdfs:label "blocks exact match" ;',
        '    rdfs:comment "True when this rule, once it fires, forbids skos:exactMatch." ;',
        "    rdfs:range xsd:boolean .",
        "",
        "maprule:isRejectionGround a owl:DatatypeProperty ;",
        '    rdfs:label "is rejection ground" ;',
        '    rdfs:comment "True when this rule is a terminal reason not to map at all." ;',
        "    rdfs:range xsd:boolean .",
        "",
    ]
    for family in FAMILIES:
        ids = family_ids(family)
        lines += [
            f"maprule:{family} a skos:Concept, skos:Collection ;",
            f'    skos:prefLabel "{_esc(FAMILY_TITLES[family])}" ;',
            f'    skos:definition "{_esc(FAMILY_SCOPE[family])}" ;',
            f"    skos:inScheme <{SCHEME_URI}> ;",
            "    skos:member " + ", ".join(f"maprule:{i}" for i in ids) + " .",
            "",
        ]
    for family in FAMILIES:
        for rid in family_ids(family):
            rule = REGISTRY[rid]
            lines += [
                f"maprule:{rid} a skos:Concept ;",
                f'    skos:notation "{rid}" ;',
                f'    skos:prefLabel "{_esc(rule.title)}" ;',
                f'    skos:definition "{_esc(rule.meaning)}" ;',
                f"    skos:broader maprule:{family} ;",
                f"    skos:inScheme <{SCHEME_URI}> ;",
                f"    maprule:blocksExactMatch {str(rule.blocks_exact_match).lower()} ;",
                f"    maprule:isRejectionGround {str(rule.rejection_ground).lower()} .",
                "",
            ]
    return "\n".join(lines)


def render_linkml() -> str:
    """Render the registry as a LinkML enum.

    Permissible value names are the bare rule ids, and each carries ``meaning`` pointing at
    the SKOS concept, so a LinkML consumer resolves the same URI the SSSOM cell contains.

    Example:
        >>> import yaml
        >>> doc = yaml.safe_load(render_linkml())
        >>> doc["enums"]["MappingCurationRule"]["permissible_values"]["SC-007"]["meaning"]
        'maprule:SC-007'
        >>> doc["prefixes"]["maprule"]["prefix_reference"]
        'https://w3id.org/mapping-rules/'
        >>> "blocks_exact_match" in doc["classes"]["CurationRuleAnnotation"]["slots"]
        True
    """
    import yaml

    permissible: dict[str, dict[str, object]] = {}
    for family in FAMILIES:
        for rid in family_ids(family):
            rule = REGISTRY[rid]
            entry: dict[str, object] = {
                "description": f"{rule.title}. {rule.meaning}",
                "meaning": f"{MAPRULE_PREFIX}:{rid}",
                "annotations": {
                    "family": family,
                    "blocks_exact_match": rule.blocks_exact_match,
                    "is_rejection_ground": rule.rejection_ground,
                },
            }
            permissible[rid] = entry

    doc = {
        "id": SCHEME_URI,
        "name": "maprule",
        "title": "Mapping curation rules",
        "description": (
            "Named, citable rules for curating and reviewing mappings. A mapping decision is "
            "only meaningful relative to the rules it was made under; these ids are what "
            "SSSOM curation_rule cells carry. Generated by `just align-valueset` from "
            "mondo_ai.align.rules — do not hand-edit."
        ),
        "license": "https://creativecommons.org/publicdomain/zero/1.0/",
        "prefixes": {
            "maprule": {"prefix_prefix": "maprule",
                        "prefix_reference": MAPRULE_URI_BASE},
            "linkml": {"prefix_prefix": "linkml",
                       "prefix_reference": "https://w3id.org/linkml/"},
            "skos": {"prefix_prefix": "skos",
                     "prefix_reference": "http://www.w3.org/2004/02/skos/core#"},
        },
        "default_prefix": "maprule",
        "default_range": "string",
        "imports": ["linkml:types"],
        "enums": {
            "MappingCurationRule": {
                "description": (
                    "Every rule in the registry, across all six families."
                ),
                "permissible_values": permissible,
            },
            "CurationRuleFamily": {
                "description": "The six families the rules are grouped into.",
                "permissible_values": {
                    f: {"description": f"{FAMILY_TITLES[f]}. {FAMILY_SCOPE[f]}",
                        "meaning": f"{MAPRULE_PREFIX}:{f}"}
                    for f in FAMILIES
                },
            },
        },
        "classes": {
            "CurationRuleAnnotation": {
                "description": (
                    "The facts a consumer needs about a cited rule in order to act on it, "
                    "rather than merely display it."
                ),
                "slots": ["rule", "family", "blocks_exact_match", "is_rejection_ground"],
            },
        },
        "slots": {
            "rule": {"range": "MappingCurationRule", "identifier": True,
                     "description": "The rule being annotated."},
            "family": {"range": "CurationRuleFamily",
                       "description": "The family the rule belongs to."},
            "blocks_exact_match": {
                "range": "boolean",
                "description": "Whether this rule, once it fires, forbids skos:exactMatch.",
            },
            "is_rejection_ground": {
                "range": "boolean",
                "description": "Whether this rule is a terminal reason not to map at all.",
            },
        },
    }
    header = (
        "# Generated by `just align-valueset` from mondo_ai.align.rules. Do not hand-edit.\n"
    )
    return header + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=96)


def render_markdown() -> str:
    """Render the registry as the human-readable documentation page.

    Example:
        >>> md = render_markdown()
        >>> "| `SC-007` |" in md
        True
        >>> "blocks `skos:exactMatch`" in md
        True
    """
    lines = [
        "# Mapping curation rules — `maprule`",
        "",
        "A registry of named, citable rules for curating and reviewing mappings.",
        "",
        "You can never determine the correctness of a mapping in the abstract — only whether, "
        "*under the curation rules declared for the set*, subject and object relate the way "
        "the predicate claims. Writing the rules down is what makes a mapping set reviewable "
        "rather than merely asserted, and giving each one a stable id is what lets a mapping "
        "row cite it in a single cell.",
        "",
        f"**Namespace:** `{MAPRULE_PREFIX}:` → `{MAPRULE_URI_BASE}`",
        "",
        "In SSSOM, rules are cited in the URI-valued `curation_rule` slot, pipe-separated:",
        "",
        "```",
        "curation_rule    maprule:EV-002|maprule:SC-001|maprule:PR-002",
        "```",
        "",
        "That row says three things a bare `skos:narrowMatch` cannot: the labels agreed after "
        "normalisation, the object turned out to be a residual rubric, and the predicate was "
        "chosen because the object is the narrower concept.",
        "",
        "## Reading the tables",
        "",
        "Two columns carry machine-readable consequences rather than description:",
        "",
        "- **blocks** — this rule, once it fires, blocks `skos:exactMatch`. The pipeline never "
        "downgrades such a match on its own authority; it routes the pair to adjudication.",
        "- **rejects** — this rule is a terminal reason not to map at all.",
        "",
        "## Generated artefacts",
        "",
        "| File | For |",
        "| --- | --- |",
        "| `vocabulary/maprule.ttl` | SKOS concept scheme, so the CURIEs resolve to definitions |",
        "| `vocabulary/maprule.yaml` | LinkML enum, to import and validate against |",
        "| `docs/maprule.md` | this page |",
        "",
        "All three are generated from `src/mondo_ai/align/rules.py` by `just align-valueset`. "
        "A test fails if they drift, so the registry the code cites and the registry the set "
        "publishes cannot disagree.",
        "",
    ]
    for family in FAMILIES:
        lines += [
            f"## Family `{family}` — {FAMILY_TITLES[family]}",
            "",
            FAMILY_SCOPE[family],
            "",
            "| rule | title | blocks | rejects | meaning |",
            "| --- | --- | --- | --- | --- |",
        ]
        for rid in family_ids(family):
            r = REGISTRY[rid]
            lines.append(
                f"| `{rid}` | {r.title} | {'✓' if r.blocks_exact_match else ''} | "
                f"{'✓' if r.rejection_ground else ''} | {r.meaning} |"
            )
        lines.append("")
    return "\n".join(lines)


#: Output path (relative to the repo root) -> renderer.
ARTEFACTS = {
    "vocabulary/maprule.ttl": render_skos,
    "vocabulary/maprule.yaml": render_linkml,
    "docs/maprule.md": render_markdown,
}


def write_all(root: str | Path = ".") -> dict[Path, bool]:
    """Write every artefact under ``root``, returning which files changed.

    Args:
        root: Repository root.

    Returns:
        Path -> whether the file's content changed.

    Example:
        >>> import tempfile, pathlib
        >>> d = pathlib.Path(tempfile.mkdtemp())
        >>> changed = write_all(d)
        >>> all(changed.values())
        True
        >>> sorted(p.name for p in changed)
        ['maprule.md', 'maprule.ttl', 'maprule.yaml']
        >>> any(write_all(d).values())
        False
    """
    root = Path(root)
    out: dict[Path, bool] = {}
    for rel, render in ARTEFACTS.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        text = render()
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        if existing != text:
            path.write_text(text, encoding="utf-8")
            out[path] = True
        else:
            out[path] = False
    return out


def check_all(root: str | Path = ".") -> list[Path]:
    """Return the artefacts whose checked-in content does not match the registry.

    Example:
        >>> import tempfile, pathlib
        >>> d = pathlib.Path(tempfile.mkdtemp())
        >>> _ = write_all(d)
        >>> check_all(d)
        []
        >>> _ = (d / "docs" / "maprule.md").write_text("stale")
        >>> [p.name for p in check_all(d)]
        ['maprule.md']
    """
    root = Path(root)
    stale: list[Path] = []
    for rel, render in ARTEFACTS.items():
        path = root / rel
        if not path.exists() or path.read_text(encoding="utf-8") != render():
            stale.append(path)
    return stale
